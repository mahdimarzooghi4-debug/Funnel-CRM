"""Workspace provisioning operations."""

from uuid import UUID, uuid4

from sqlalchemy.ext.asyncio import AsyncSession

from funnel_crm.platform.models import OrganizationUnit, Workspace, WorkspaceCRMSettings


async def create_workspace(
    session: AsyncSession,
    *,
    display_name: str,
    workspace_id: UUID | None = None,
    root_organization_id: UUID | None = None,
) -> Workspace:
    """Add a workspace and its root organization in the caller's transaction.

    Both identifiers are generated by the server unless explicitly supplied by
    trusted internal code. The deferred composite foreign key guarantees that
    the root organization belongs to this workspace at transaction commit.
    """
    normalized_name = display_name.strip()
    if not normalized_name:
        raise ValueError("display_name must not be empty")

    tenant_id = workspace_id or uuid4()
    root_id = root_organization_id or uuid4()

    workspace = Workspace(
        id=tenant_id,
        display_name=normalized_name,
        root_organization_id=root_id,
        root_organization_type="root",
    )
    root = OrganizationUnit(
        id=root_id,
        tenant_id=tenant_id,
        parent_id=None,
        name=normalized_name,
        unit_type="root",
    )

    # The workspace-to-root constraint is deferred. Persist the workspace first
    # so the root's immediate tenant foreign key is satisfied, then persist root.
    session.add(workspace)
    await session.flush()
    session.add(root)
    session.add(WorkspaceCRMSettings(tenant_id=tenant_id))
    await session.flush()
    return workspace
